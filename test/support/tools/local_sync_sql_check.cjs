// Runs the exact SQL exported by Dart against a real SQLite engine.
// No packages, native downloads, business databases or network connections.
const {DatabaseSync}=require('node:sqlite');
const fs=require('node:fs');
const assert=require('node:assert/strict');
const input=JSON.parse(fs.readFileSync(process.argv[2],'utf8'));
const business=fs.readFileSync('lib/database/database_helper.dart','utf8');
const db=new DatabaseSync(':memory:');
const definitions=[...business.matchAll(/CREATE TABLE(?: IF NOT EXISTS)?\s+(\w+)\s*\([\s\S]*?\)(?=\s*''')/g)];
for(const m of definitions) db.exec(m[0]);
assert.equal(definitions.length,13,'Expected all thirteen original business tables');
db.exec("INSERT INTO users(id,username) VALUES(1,'User 1'),(2,'User 2')");
db.exec("INSERT INTO ledgers(id,name,user_id) VALUES(1,'Existing ledger',1)");
db.exec("INSERT INTO categories(id,name,type,user_id) VALUES(1,'Food','expense',1)");
db.exec("INSERT INTO tags(id,name,user_id) VALUES(1,'Existing tag',1)");
db.exec("INSERT INTO expense_records(id,ledger_id,type,amount,category_id,date) VALUES(1,1,'expense',20.5,1,'2026-10-15T12:00:00')");
const before=db.prepare('SELECT * FROM expense_records').all();
for(const sql of [...input.create,...input.backfill])db.exec(sql);
assert.deepEqual(db.prepare('SELECT * FROM expense_records').all(),before);
function object(table,key){return db.prepare('SELECT * FROM local_sync_objects WHERE table_name=? AND local_key=?').get(table,String(key));}
const first=object('expense_records',1);
assert.equal(first.owner_user_id,1,'Old null owner must resolve through ledger');
assert.equal(first.object_uid.length,32);
db.exec("UPDATE expense_records SET note='First edit' WHERE id=1");
const versionA=object('expense_records',1).local_version;
db.exec("UPDATE expense_records SET note='Second edit' WHERE id=1");
const versionB=object('expense_records',1).local_version;
assert(versionB>versionA);
assert.equal(object('expense_records',1).object_uid,first.object_uid);
assert.equal(db.prepare(input.acknowledge).run(first.object_uid,versionA,1).changes,0,'Stale receipt removed new edit');
assert.equal(db.prepare(input.acknowledge).run(first.object_uid,versionB,2).changes,0,'Other user cleared queue');
assert.equal(db.prepare(input.acknowledge).run(first.object_uid,versionB,1).changes,1);
const queueBefore=db.prepare('SELECT * FROM local_sync_queue ORDER BY object_uid').all();
db.exec("BEGIN; UPDATE expense_records SET note='Rolled back' WHERE id=1; INSERT INTO expense_records(id,ledger_id,type,amount,category_id,date,user_id) VALUES(2,1,'expense',1,1,'2026-10-15',1); ROLLBACK");
assert.deepEqual(db.prepare('SELECT * FROM local_sync_queue ORDER BY object_uid').all(),queueBefore);
assert.equal(object('expense_records',2),undefined);
db.exec("INSERT INTO record_tags VALUES(1,1)");
const tag=object('record_tags','1:1');assert.equal(tag.owner_user_id,1);
db.exec("DELETE FROM record_tags WHERE record_id=1 AND tag_id=1");
assert.equal(object('record_tags','1:1').deleted,1);
db.exec("INSERT INTO record_tags VALUES(1,1)");
assert.equal(object('record_tags','1:1').object_uid,tag.object_uid);
assert.equal(object('record_tags','1:1').deleted,0);
db.exec("INSERT INTO recurring_bills(id,user_id,title,type,amount_cents,ledger_id,category_id,day_of_month,start_date,active_from,created_at,updated_at) VALUES(1,1,'Rent','expense',10000,1,1,15,'2026-10-15','2026-10-15','2026-10-15','2026-10-15')");
assert(object('recurring_bills',1));
db.exec('DELETE FROM expense_records WHERE id=1');
assert.equal(object('expense_records',1).deleted,1);
assert.equal(object('expense_records',1).object_uid,first.object_uid);
const scope=db.prepare('SELECT installation_scope FROM local_sync_control').get().installation_scope;
const tombstoneCount=db.prepare('SELECT COUNT(*) AS n FROM local_sync_objects WHERE deleted=1').get().n;
db.exec('BEGIN');db.exec(input.pause);
db.exec("INSERT INTO ledgers(id,name,user_id) VALUES(99,'Restore test',1)");
assert.equal(object('ledgers',99),undefined);
for(const sql of [...input.reset,...input.backfill])db.exec(sql);
assert.notEqual(db.prepare('SELECT installation_scope FROM local_sync_control').get().installation_scope,scope);
db.exec('ROLLBACK');
assert.equal(db.prepare('SELECT installation_scope FROM local_sync_control').get().installation_scope,scope);
assert.equal(db.prepare('SELECT COUNT(*) AS n FROM local_sync_objects WHERE deleted=1').get().n,tombstoneCount);
db.exec('BEGIN');db.exec(input.pause);
for(const sql of [...input.reset,...input.backfill])db.exec(sql);
db.exec('COMMIT');
assert.notEqual(db.prepare('SELECT installation_scope FROM local_sync_control').get().installation_scope,scope);
assert.equal(db.prepare('SELECT COUNT(*) AS n FROM local_sync_objects WHERE deleted=1').get().n,0);
assert.equal(db.prepare('SELECT capture_enabled FROM local_sync_control').get().capture_enabled,1);
db.close();
console.log('SQLite integration passed: v7 rows preserved, stable identities, null-owner backfill, direct-write capture, coalescing, stale/cross-user receipts, transaction rollback, tag relations, recurring writes, deletion tombstones, restore scope reset and rollback.');
